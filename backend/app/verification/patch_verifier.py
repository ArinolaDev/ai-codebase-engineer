"""
Behavioral verification of a proposed fix (Phase 8, "lite" - no Docker yet).

  1. Copy the project to a temp folder (venv, .git, data, .env are skipped).
  2. Run tests on the ORIGINAL code in the copy.
  3. Write the patched file into the copy and run the SAME tests again.
  4. Compare: a test that passed before and fails after is a regression.

Tests come from you (`test_code`) and/or are generated by the model for the
patched function (`auto_tests`). Auto tests are "characterization tests": we
keep only the ones that pass on the ORIGINAL code, so they pin down current
behavior. A fix that legitimately changes behavior (e.g. a different hash
algorithm) WILL show up as a regression - that is the point.

SAFETY: this runs project code and model-written tests on your machine.
Subprocess + timeout + minimal env, but NOT a sandbox. Trusted projects only,
until the Docker sandbox exists.
"""

import ast
import os
import re
import shutil
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from app.analysis.fixer import FixError, find_scope, propose_fix
from app.testgen.generator import (
    TestGenError, extract_function, generate_test_code, keep_only, list_test_names,
)
from app.testgen.runner import run_tests

_SKIP_DIRS = {"venv", ".venv", "env", "node_modules", ".git", "__pycache__", "data", ".idea", ".vscode"}
_SKIP_FILES = {".env"}
MAX_FILES = 3000
MAX_BYTES = 50 * 1024 * 1024


class VerifyError(Exception):
    pass


@dataclass
class VerifyResult:
    verdict: str                 # safe_by_tests | unsafe | untested | rejected
    summary: str
    proposal: object             # FixProposal
    tests_before_passed: list[str] = field(default_factory=list)
    tests_after_passed: list[str] = field(default_factory=list)
    regressions: dict[str, str] = field(default_factory=dict)   # test -> why it now fails
    newly_passing: list[str] = field(default_factory=list)
    test_code_used: str | None = None
    notes: list[str] = field(default_factory=list)


def copy_project(src: str, dst: str) -> None:
    src_p, dst_p = Path(src).resolve(), Path(dst)
    files, total = 0, 0
    for dirpath, dirnames, filenames in os.walk(src_p):
        dirnames[:] = [d for d in dirnames if d not in _SKIP_DIRS]
        rel = Path(dirpath).relative_to(src_p)
        (dst_p / rel).mkdir(parents=True, exist_ok=True)
        for name in filenames:
            if name in _SKIP_FILES or name.endswith((".pyc", ".zip")):
                continue
            f = Path(dirpath) / name
            files += 1
            total += f.stat().st_size
            if files > MAX_FILES or total > MAX_BYTES:
                raise VerifyError(
                    f"Project is too large to copy for verification "
                    f"(limit {MAX_FILES} files / {MAX_BYTES // (1024 * 1024)} MB, excluding venv/data/.git)."
                )
            shutil.copy2(f, dst_p / rel / name)


def _retarget_path(test_code: str, new_root: str) -> str:
    """Generated tests hard-code the project root in a sys.path line; point it at the copy."""
    line = f"sys.path.insert(0, {new_root!r})"
    if re.search(r"^sys\.path\.insert\(0, .*\)\s*$", test_code, re.MULTILINE):
        return re.sub(r"^sys\.path\.insert\(0, .*\)\s*$", lambda m: line, test_code, count=1, flags=re.MULTILINE)
    return f"import sys\n{line}\n" + test_code


def _top_level_function_at(source: str, line: int) -> str | None:
    start, _end, is_function = find_scope(source, line)
    if not is_function:
        return None
    for node in ast.parse(source).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.lineno <= start <= (node.end_lineno or node.lineno):
            return node.name
    return None   # a method, not a top-level function


def verify_fix(project_root: str, rel_path: str, line: int, rule_id: str,
               test_code: str | None = None, auto_tests: bool = False,
               fix_llm=None, test_llm=None, fix_feedback: str | None = None,
               progress=None) -> VerifyResult:
    _p = progress or (lambda *a, **k: None)
    _p("fix", "Proposing a fix")
    proposal = propose_fix(project_root, rel_path, line, rule_id, llm=fix_llm, feedback=fix_feedback)
    if not proposal.verified:
        return VerifyResult(
            verdict="rejected", proposal=proposal,
            summary="The proposed patch failed its own checks, so it was not tried against tests.",
        )

    notes: list[str] = []
    old_source = (Path(project_root).resolve() / rel_path).read_text(encoding="utf-8", errors="replace")

    with tempfile.TemporaryDirectory(prefix="aice_verify_") as tmp:
        copy_root = str(Path(tmp) / "project")
        try:
            copy_project(project_root, copy_root)
        except OSError as e:
            raise VerifyError(f"Could not copy the project: {e}")
        target_file = Path(copy_root) / rel_path

        # assemble the test file(s)
        code = None
        if test_code and test_code.strip():
            code = _retarget_path(test_code, str(Path(copy_root).resolve()))
            try:
                list_test_names(code)
            except SyntaxError as e:
                raise VerifyError(f"Your test_code isn't valid Python (line {e.lineno}: {e.msg}).")
        elif auto_tests:
            _p("gen_tests", "Asking the model to write tests")
            fn = _top_level_function_at(old_source, line)
            if fn is None:
                notes.append("auto_tests only supports fixes inside a top-level function; "
                             "this one is a method or module-level code, so no tests were generated.")
            else:
                try:
                    target = extract_function(copy_root, rel_path, fn)
                    code = generate_test_code(target, copy_root, llm=test_llm)
                except TestGenError as e:
                    notes.append(f"Could not generate tests for `{fn}`: {e}")

        if code is None:
            return VerifyResult(
                verdict="untested", proposal=proposal,
                summary="No tests were run, so the patch is only checked by the scanner, not by behavior. "
                        "Provide test_code or set auto_tests=true.",
                notes=notes,
            )

        _p("tests_before", "Running tests on the original code")
        before = run_tests(copy_root, code)
        if before.run_error:
            return VerifyResult(
                verdict="untested", proposal=proposal, test_code_used=code, notes=notes,
                summary="The tests could not run on the ORIGINAL code, so nothing could be compared: "
                        + before.run_error.splitlines()[0],
            )
        if not before.passed:
            return VerifyResult(
                verdict="untested", proposal=proposal, test_code_used=code, notes=notes,
                summary="None of the tests passed on the original code, so there is no baseline to compare. "
                        f"Failures: {dict(list(before.failed.items())[:3])}",
            )

        # keep only tests that pass on the original (the baseline)
        baseline = keep_only(code, before.passed)
        if before.failed:
            notes.append(f"{len(before.failed)} test(s) already failed on the original code and were ignored: "
                         + ", ".join(sorted(before.failed)))

        target_file.write_text(proposal.new_source, encoding="utf-8")
        _p("tests_after", "Running the same tests on the patched code")
        after = run_tests(copy_root, baseline)

        if after.run_error:
            return VerifyResult(
                verdict="unsafe", proposal=proposal, test_code_used=baseline,
                tests_before_passed=sorted(before.passed), notes=notes,
                regressions={"<module>": "After the patch the tests could not run (import error?): "
                                         + after.run_error.splitlines()[0]},
                summary="The patch breaks the module: the tests no longer run.",
            )

        regressions = {}
        for name in before.passed:
            if name not in after.passed:
                regressions[name] = after.failed.get(name, "did not pass after the patch")

        if regressions:
            verdict = "unsafe"
            summary = (f"{len(regressions)} test(s) that passed on the original code FAIL after the patch. "
                       "Either the patch changes behavior you rely on, or those tests encode the old bug.")
        else:
            verdict = "safe_by_tests"
            summary = (f"All {len(before.passed)} baseline test(s) pass before and after the patch. "
                       "That is evidence, not proof: it only covers what the tests cover.")

        return VerifyResult(
            verdict=verdict, summary=summary, proposal=proposal,
            tests_before_passed=sorted(before.passed), tests_after_passed=sorted(after.passed),
            regressions=regressions, newly_passing=[], test_code_used=baseline, notes=notes,
        )
